"""Compatibility alias for the renamed distribution.

The package was renamed to ``meetkai-mka1`` (module ``meetkai_mka1``), but the
published documentation and existing integrations import ``mka1``::

    from mka1 import SDK
    from mka1.errors import SDKDefaultError

This module keeps both names working, and resolving to the SAME module
objects — planting the real modules in ``sys.modules`` under the old names
rather than re-importing them, so exception classes and ``isinstance`` checks
are identical across the two spellings.

NOT generated by Speakeasy — hand-maintained, survives regeneration (only
files tracked in .speakeasy/gen.lock are managed by the generator).
"""

import importlib
import sys

import meetkai_mka1

# Re-export the top-level surface (SDK, models, errors, VERSION, ...).
from meetkai_mka1 import *  # noqa: F401,F403

# Importing meetkai_mka1 above eagerly loads its full submodule tree (its
# __init__ pulls in sdk -> every route module, models, errors, ...). Mirror
# every loaded submodule under the old prefix so `import mka1.x.y` and
# `from mka1.errors import ...` hit the sys.modules cache and return the
# canonical module objects instead of loading duplicate copies.
_REAL = "meetkai_mka1"
_ALIAS = __name__
for _name in list(sys.modules):
    if _name == _REAL or _name.startswith(_REAL + "."):
        _alias_name = _ALIAS + _name[len(_REAL) :]
        if _alias_name != _ALIAS:
            sys.modules.setdefault(_alias_name, sys.modules[_name])


def __getattr__(name: str):
    """Fallback for any submodule not loaded during the eager mirror above."""
    module = importlib.import_module(f"{_REAL}.{name}")
    sys.modules[f"{_ALIAS}.{name}"] = module
    return module
